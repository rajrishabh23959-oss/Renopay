// Helper for today's date formatted as YYYY-MM-DD
export function getTodayString() {
  const d = new Date();
  return d.toISOString().slice(0, 10);
}

export function getNextDayString(daysAhead = 1) {
  const d = new Date();
  d.setDate(d.getDate() + daysAhead);
  return d.toISOString().slice(0, 10);
}

